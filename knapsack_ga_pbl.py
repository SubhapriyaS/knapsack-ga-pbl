best, best_history, mean_history, elapsed = genetic_algorithm()

display_solution("GENETIC ALGORITHM SOLUTION", best)

greedy = greedy_solution()
display_solution("GREEDY BASELINE SOLUTION", greedy)

exact = exact_solution()
display_solution("EXACT OPTIMAL SOLUTION", exact)

print("\nGA execution time:", round(elapsed, 4), "seconds")
print("GA reached optimal value:", fitness(best) == fitness(exact))


