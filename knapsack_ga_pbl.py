import random
import time
import csv
import matplotlib.pyplot as plt

# ============================================================
# EVOLUTIONARY COMPUTING PBL
# Knapsack Optimization using a Genetic Algorithm
# ============================================================

ITEMS = [
    ("Laptop", 8, 20),
    ("Books", 3, 8),
    ("Headphones", 2, 5),
    ("Camera", 5, 12),
    ("Water Bottle", 1, 3),
    ("Jacket", 4, 9),
    ("Charger", 1, 4),
    ("Shoes", 6, 13),
    ("Snacks", 2, 4),
    ("Notebook", 1, 2),
    ("Power Bank", 3, 7),
    ("Tablet", 5, 11)
]

CAPACITY = 25
WEIGHTS = [item[1] for item in ITEMS]
VALUES = [item[2] for item in ITEMS]
N = len(ITEMS)


# ---------------- FITNESS FUNCTION ----------------
def fitness(chromosome):
    total_weight = sum(
        chromosome[i] * WEIGHTS[i] for i in range(N)
    )
    total_value = sum(
        chromosome[i] * VALUES[i] for i in range(N)
    )

    if total_weight > CAPACITY:
        return 0

    return total_value


def total_weight(chromosome):
    return sum(
        chromosome[i] * WEIGHTS[i] for i in range(N)
    )


# ---------------- CREATE INITIAL POPULATION ----------------
def create_chromosome():
    chromosome = [random.randint(0, 1) for _ in range(N)]

    # Repair overweight solutions
    while total_weight(chromosome) > CAPACITY:
        selected = [i for i in range(N) if chromosome[i] == 1]
        chromosome[random.choice(selected)] = 0

    return chromosome


def create_population(population_size):
    return [create_chromosome() for _ in range(population_size)]


# ---------------- PARENT SELECTION ----------------
def tournament_selection(population):
    contestants = random.sample(population, 3)
    return max(contestants, key=fitness)


# ---------------- CROSSOVER ----------------
def crossover(parent1, parent2, crossover_rate=0.8):
    if random.random() > crossover_rate:
        return parent1[:], parent2[:]

    point = random.randint(1, N - 1)
    child1 = parent1[:point] + parent2[point:]
    child2 = parent2[:point] + parent1[point:]

    return child1, child2


# ---------------- MUTATION ----------------
def mutate(chromosome, mutation_rate=0.03):
    child = chromosome[:]

    for i in range(N):
        if random.random() < mutation_rate:
            child[i] = 1 - child[i]

    # Repair overweight offspring
    while total_weight(child) > CAPACITY:
        selected = [i for i in range(N) if child[i] == 1]
        child[random.choice(selected)] = 0

    return child


# ---------------- GENETIC ALGORITHM ----------------
def genetic_algorithm(
    population_size=80,
    generations=200,
    mutation_rate=0.03,
    crossover_rate=0.8,
    seed=42
):
    random.seed(seed)
    population = create_population(population_size)

    best_history = []
    mean_history = []

    best = max(population, key=fitness)

    start_time = time.perf_counter()

    for generation in range(generations):
        # Elitism: preserve the best solution
        current_best = max(population, key=fitness)

        if fitness(current_best) > fitness(best):
            best = current_best[:]

        scores = [fitness(individual) for individual in population]
        best_history.append(max(scores))
        mean_history.append(sum(scores) / len(scores))

        new_population = [best[:]]

        while len(new_population) < population_size:
            parent1 = tournament_selection(population)
            parent2 = tournament_selection(population)

            child1, child2 = crossover(
                parent1, parent2, crossover_rate
            )

            child1 = mutate(child1, mutation_rate)
            child2 = mutate(child2, mutation_rate)

            new_population.append(child1)

            if len(new_population) < population_size:
                new_population.append(child2)

        population = new_population

    # Check the final population too
    current_best = max(population, key=fitness)

    if fitness(current_best) > fitness(best):
        best = current_best[:]

    elapsed = time.perf_counter() - start_time

    return best, best_history, mean_history, elapsed


# ---------------- GREEDY BASELINE ----------------
def greedy_solution():
    chromosome = [0] * N

    # Choose items by value-to-weight ratio
    order = sorted(
        range(N),
        key=lambda i: VALUES[i] / WEIGHTS[i],
        reverse=True
    )

    remaining_capacity = CAPACITY

    for i in order:
        if WEIGHTS[i] <= remaining_capacity:
            chromosome[i] = 1
            remaining_capacity -= WEIGHTS[i]

    return chromosome


# ---------------- EXACT SOLUTION ----------------
def exact_solution():
    # Dynamic programming: finds the true optimal value
    dp = [[0] * (CAPACITY + 1) for _ in range(N + 1)]

    for i in range(1, N + 1):
        weight = WEIGHTS[i - 1]
        value = VALUES[i - 1]

        for capacity in range(CAPACITY + 1):
            dp[i][capacity] = dp[i - 1][capacity]

            if weight <= capacity:
                dp[i][capacity] = max(
                    dp[i][capacity],
                    dp[i - 1][capacity - weight] + value
                )

    chromosome = [0] * N
    remaining_capacity = CAPACITY

    for i in range(N, 0, -1):
        if dp[i][remaining_capacity] != dp[i - 1][remaining_capacity]:
            chromosome[i - 1] = 1
            remaining_capacity -= WEIGHTS[i - 1]

    return chromosome


# ---------------- DISPLAY SELECTED ITEMS ----------------
def display_solution(title, chromosome):
    print("\n" + title)
    print("-" * len(title))

    for i, selected in enumerate(chromosome):
        if selected:
            print(
                f"{ITEMS[i][0]:15s} "
                f"Weight: {WEIGHTS[i]:2d} "
                f"Value: {VALUES[i]:2d}"
            )

    print("Total weight:", total_weight(chromosome))
    print("Total value:", fitness(chromosome))


